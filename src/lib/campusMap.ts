export function searchCampusPlaces(
  query: string,
  options?: {
    category?: string;
    floorLevel?: number | "all";
  }
): CampusPlace[] {
  let places = CAMPUS_PLACES;

  if (options?.category && options.category !== "all") {
    places = places.filter(
      (p) => p.category === options.category || p.zone === options.category
    );
  }

  if (options?.floorLevel !== undefined && options.floorLevel !== "all") {
    places = places.filter((p) => p.floorLevel === options.floorLevel);
  }

  const rawQ = query.trim().toLowerCase();
  if (!rawQ) return places;

  const cleanQ = rawQ.replace(/\s+/g, " ");
  const strippedQ = rawQ.replace(/[-\s]/g, "");

  return places.filter((place) => {
    const hay = `${place.name} ${place.shortName || ""} ${place.code || ""} ${place.aliases.join(" ")} ${place.hint} ${place.terrace} ${place.floor || ""} Level ${place.floorLevel !== undefined ? place.floorLevel : ""}`.toLowerCase();
    const strippedHay = hay.replace(/[-\s]/g, "");

    return (
      hay.includes(cleanQ) ||
      strippedHay.includes(strippedQ) ||
      place.aliases.some((alias) => {
        const a = alias.toLowerCase();
        return a.includes(cleanQ) || a.replace(/[-\s]/g, "").includes(strippedQ);
      })
    );
  });
}

